'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { LocalRagIndex } = require('../electron/rag/index.cjs');
async function main() {
  const largeFileCount = Number(process.argv.find((value) => value.startsWith('--files='))?.slice(8) || 800);
  if (!Number.isInteger(largeFileCount) || largeFileCount < 1 || largeFileCount > 10000) throw new Error('files must be 1..10000');
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'rag-scan-worker-'));
  const indexes = [];
  try {
    fs.mkdirSync(path.join(root, 'src/cache'), { recursive: true });
    fs.writeFileSync(path.join(root, 'src/cache/config.ts'), 'export const limit = 5;\n');
    fs.writeFileSync(path.join(root, 'src/use.ts'), "import { limit } from './cache/config';\nexport function check(n) { return n < limit; }\n");
    fs.mkdirSync(path.join(root, 'assets'), { recursive: true });
    for (let i = 0; i < 40; i++) fs.writeFileSync(path.join(root, 'assets', 'image' + i + '.png'), Buffer.from([1, 2, 3]));
    const capped = new LocalRagIndex(root, { indexWorker: true, maxFiles: 2 }); indexes.push(capped);
    const capResult = await capped.retrieve('limit', { mode: 'file' });
    assert.equal(capResult.stats.indexedFiles, 2, 'Ignored assets must not consume the source file quota');
    const sync = new LocalRagIndex(root, { indexWorker: false });
    const worker = new LocalRagIndex(root, { indexWorker: true }); indexes.push(sync, worker);
    const a = await sync.retrieve('check limit call', { mode: 'file', hops: 1 });
    const b = await worker.retrieve('check limit call', { mode: 'file', hops: 1 });
    assert.equal(b.stats.mode, 'worker');
    assert.deepEqual(b.results.map((source) => source.citation), a.results.map((source) => source.citation));
    const warm = await worker.retrieve('limit', { mode: 'file' });
    assert.equal(warm.stats.changedFiles, 0); assert.equal(warm.stats.reusedFiles, 2);
    const file = path.join(root, 'src/cache/config.ts'), stat = fs.statSync(file);
    fs.writeFileSync(file, 'export const limit = 9;\n'); fs.utimesSync(file, stat.atime, stat.mtime);
    worker.invalidate('src/cache/config.ts');
    const changed = await worker.retrieve('limit', { mode: 'file' });
    assert.ok(changed.results.some((source) => source.excerpt.includes('limit = 9')));
    assert.equal(changed.stats.changedFiles, 1);
    fs.unlinkSync(file);
    const removed = await worker.retrieve('limit', { mode: 'file' });
    assert.equal(removed.stats.removedFiles, 1);
    assert.ok(!removed.results.some((source) => source.path === 'src/cache/config.ts'));
    fs.writeFileSync(file, 'export const limit = 5;\n');
    const racing = new LocalRagIndex(root, { indexWorker: true }); indexes.push(racing);
    const raced = racing.retrieve('limit', { mode: 'file' });
    const edit = setTimeout(() => { fs.writeFileSync(file, 'export const limit = 8;\n'); racing.invalidate('src/cache/config.ts'); }, 10);
    const raceResult = await raced; clearTimeout(edit);
    assert.equal(racing.fileCache.size, 2, 'Discarding a stale first scan must not lose unchanged files');
    assert.ok(raceResult.results.some((source) => source.excerpt.includes('limit = 8')));
    const lateCancel = new LocalRagIndex(root, { indexWorker: true }); indexes.push(lateCancel);
    const lateSignal = new AbortController();
    const lateRequest = lateCancel.retrieve('limit', { mode: 'file', runtime: { signal: lateSignal.signal } });
    const attach = setInterval(() => {
      if (!lateCancel.scanClient?.worker) return;
      clearInterval(attach);
      lateCancel.scanClient.worker.on('message', (data) => { if (data.type === 'done') lateSignal.abort(); });
    }, 1);
    await assert.rejects(lateRequest, (error) => error instanceof Error && error.name === 'AbortError');
    clearInterval(attach);
    assert.equal(lateCancel.fileCache.size, 0);
    const afterCancel = await lateCancel.retrieve('limit', { mode: 'file' });
    assert.equal(afterCancel.stats.indexedFiles, 2);
    assert.equal(lateCancel.fileCache.size, 2, 'A cancelled completed scan must resync the entire worker cache on next use');
    fs.mkdirSync(path.join(root, 'large'), { recursive: true });
    const body = Array.from({ length: 100 }, (_, i) => `  const value${i} = input + ${i};`).join('\n');
    for (let i = 0; i < largeFileCount; i++) fs.writeFileSync(path.join(root, 'large', 'f' + i + '.ts'), `export function compute${i}(input) {\n${body}\n  return input;\n}\n`);
    const large = new LocalRagIndex(root, { indexWorker: true, maxFiles: Math.max(2000, largeFileCount + 10) }); indexes.push(large);
    let ticks = 0, maxGap = 0, previous = performance.now();
    const heartbeat = setInterval(() => { const now = performance.now(); ticks++; maxGap = Math.max(maxGap, now - previous); previous = now; }, 10);
    const started = performance.now();
    const big = await large.retrieve('compute42', { mode: 'file' });
    // Let an overdue heartbeat run after final commit and ranking, not only while the worker is busy.
    await new Promise((resolve) => setTimeout(resolve, 15));
    clearInterval(heartbeat);
    assert.ok(ticks >= 10, 'Main event loop must remain responsive during AST indexing');
    assert.ok(big.results.length && big.stats.indexedFiles >= largeFileCount);
    console.log(JSON.stringify({ scenario: largeFileCount + ' TypeScript files, worker scanning and AST', indexedFiles: big.stats.indexedFiles,
      ms: performance.now() - started, heartbeatTicks: ticks, maxHeartbeatGapMs: maxGap,
      commitMs: big.stats.commitDurationMs, scoreMs: big.stats.lexicalScoringMs }));
    if (process.argv.includes('--scale-only')) return;
    const cancelled = new LocalRagIndex(root, { indexWorker: true }); indexes.push(cancelled);
    const controller = new AbortController();
    const pending = cancelled.retrieve('compute42', { mode: 'file', runtime: { signal: controller.signal } });
    const timer = setTimeout(() => controller.abort(), 10);
    await assert.rejects(pending, (error) => error instanceof Error && error.name === 'AbortError'); clearTimeout(timer);
    assert.equal(cancelled.fileCache.size, 0, 'Cancelled scan must not commit partial entries');
    const queued = new LocalRagIndex(root, { indexWorker: true }); indexes.push(queued);
    const active = queued.retrieve('compute42', { mode: 'file' });
    const stopped = new AbortController();
    const second = queued.retrieve('compute1', { mode: 'file', runtime: { signal: stopped.signal } });
    stopped.abort(); await assert.rejects(second, (error) => error instanceof Error && error.name === 'AbortError');
    assert.ok((await active).results.length, 'Cancelling a queued caller must not cancel another scan');
    console.log('RAG SCAN WORKER: PASS (sync equivalence, graph, warm reuse, forced invalidation, delete, heartbeat, cancellation and queue isolation)');
  } finally { for (const index of indexes) index.close(); fs.rmSync(root, { recursive: true, force: true }); }
}
main().catch((error) => { console.error(error); process.exitCode = 1; });

'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const crypto = require('node:crypto');
const moduleRoot = process.env.CODENODE_PACKAGED_ASAR || path.join(__dirname, "../..");
const { AgentToolContext } = require(path.join(moduleRoot, 'electron/tools/context.cjs'));
const toolkit = require(path.join(moduleRoot, 'electron/tools/toolkit.cjs'));
const { atomicWriteFile } = require(path.join(moduleRoot, 'electron/atomicFile.cjs'));
const { syntaxCheck } = require(path.join(moduleRoot, 'electron/safeEditing.cjs'));
const { config, writeSettings, parseSettings } = require(path.join(moduleRoot, 'electron/editingSettings.cjs'));
const { CodeVerifier, captureInputs } = require(path.join(moduleRoot, 'electron/codeVerification.cjs'));
const sandbox = require(path.join(moduleRoot, 'electron/sandbox.cjs'));
const hash = value => crypto.createHash('sha256').update(value).digest('hex');

async function main() {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'codenode-coding-safety-'));
  const file = path.join(root, 'calc.cjs');
  const write = (name, value) => fs.writeFileSync(path.join(root, name), value);
  const policy = sandbox.resolvePolicy({ mode: 'off' }, { projectRoot: root, userDataDir: root });
  sandbox.setDefaultPolicy(policy);
  const context = new AgentToolContext({ projectRoot: root, confirm: async()=>true, sandbox: policy });
  const registry = toolkit.buildDefaultRegistryWithConfig({ ragEnabled: false });
  try {
    write('calc.cjs', '\uFEFFconst value = 1;\r\n');
    const before = fs.readFileSync(file);
    let result = await registry.execute('edit_file', { path: 'calc.cjs', oldText: 'value' }, context);
    assert.equal(result.ok, false); assert.deepEqual(fs.readFileSync(file), before, 'Omitted newText cannot silently delete');
    result = await registry.execute('edit_file', { path: 'calc.cjs', oldText: '1;', newText: '{;' }, context);
    assert.equal(result.ok, false); assert.deepEqual(fs.readFileSync(file), before); assert.equal(fs.existsSync(file+'.bak'),false);
    result = await registry.execute('edit_file', { path: 'calc.cjs', replacements: [{oldText:'const value',newText:'const'},{oldText:'const =',newText:'const result ='}] }, context);
    assert.equal(result.ok, true, result.text); assert.equal(result.data.replaced, 2);
    assert.equal(fs.readFileSync(file, 'utf8'), '\uFEFFconst result = 1;\r\n', 'BOM and CRLF survive splicing');
    write('ambiguous.txt', 'same\nsame\n');
    assert.equal((await registry.execute('edit_file',{path:'ambiguous.txt',oldText:'same',newText:'new'},context)).ok,false);
    assert.equal((await registry.execute('edit_file',{path:'ambiguous.txt',oldText:'same',newText:'new',occurrence:0},context)).data.replaced,2);
    const raced = new AgentToolContext({ projectRoot:root, confirm:async()=>{write('calc.cjs','const result = 1;\n// external\n');return true;} });
    assert.equal((await registry.execute('edit_file',{path:'calc.cjs',oldText:'1;',newText:'2;'},raced)).failure.code,'CONFLICT_STALE');
    assert.match(fs.readFileSync(file,'utf8'),/external/);
    const stable = fs.readFileSync(file), originalSync = fs.fsyncSync;
    try {
      fs.fsyncSync = fd => { originalSync(fd); write('calc.cjs','const external = 3;\n'); };
      assert.throws(()=>atomicWriteFile(file,'const replaced = 4;\n','utf8',{expectedSha256:hash(stable)}),error=>!!error && typeof error==='object' && 'code' in error && error.code==='CONFLICT_STALE');
    } finally { fs.fsyncSync=originalSync; }
    assert.equal(fs.readFileSync(file,'utf8'),'const external = 3;\n');
    assert.equal(fs.readdirSync(root).filter(name=>name.endsWith('.tmp')).length,0);
    write('long.cjs',Array.from({length:450},(_,i)=>'const n'+i+' = '+i+';').join('\n'));
    const long = fs.readFileSync(path.join(root,'long.cjs'));
    assert.equal((await registry.execute('write_file',{path:'long.cjs',content:'const n0 = 0;'},context)).ok,false);
    assert.deepEqual(fs.readFileSync(path.join(root,'long.cjs')),long, 'Syntactically valid truncation is still refused');
    assert.equal(syntaxCheck('good.mjs','export const ok = 1;').status,'passed');
    assert.equal(syntaxCheck('bad.js','const value: number = 1;').status,'failed');
    assert.equal(syntaxCheck('bad.json','{"broken":}').status,'failed');
    writeSettings(root,{...config.defaults,lintCommand:'node -e "process.exit(0)"',timeoutSeconds:8});
    const properties = Object.fromEntries(fs.readFileSync(path.join(root,'.codenode/agent.properties'),'utf8').trim().split('\n').map(line=>{const at=line.indexOf('=');return[line.slice(0,at),line.slice(at+1)];}));
    assert.equal(parseSettings(properties).timeoutSeconds,8);
    assert.equal(parseSettings(properties).lintCommand,'node -e "process.exit(0)"');
    assert.equal((await registry.execute('find_definition',{symbol:'external'},new AgentToolContext({projectRoot:root,ragConfig:{enabled:false}}))).ok,true);

    write('calc.cjs','module.exports = { value: 2 };\n');
    write('calc.test.cjs',"require('node:assert/strict').equal(require('./calc.cjs').value,2);\n");
    const settings={...config.defaults,lintCommand:'node -e "process.exit(0)"',timeoutSeconds:8};
    const verifier = new CodeVerifier(root,settings,{policy,context});
    verifier.observe({name:'edit_file',ok:true,data:{path:'calc.cjs'}});
    let report=await verifier.flush();
    assert.equal(report.status,'passed',JSON.stringify(report)); assert.equal(report.verified,true);
    assert.match(report.checks.find(check=>check.kind==='test').command,/calc.test.cjs/);
    const stat = fs.statSync(file);
    write('calc.cjs','module.exports = { value: 3 };\n');fs.utimesSync(file,stat.atime,stat.mtime);
    assert.equal(verifier.freshness().status,'stale','Same-stat changes invalidate receipts');
    report=await verifier.flush();assert.equal(report.status,'failed');assert.equal(verifier.blocked(),true);
    write('calc.cjs','module.exports = { value: 2 };\n');verifier.observe({name:'edit_file',ok:true,data:{path:'calc.cjs'}});
    report=await verifier.flush();assert.equal(report.status,'passed');
    write('tsconfig.json','{"strict":true}');assert.equal(verifier.freshness().status,'stale','Config changes invalidate receipts');
    report=await verifier.flush();assert.equal(report.status,'not_run');assert.equal(report.verified,false);assert.equal(verifier.blocked(),true);
    const none = new CodeVerifier(root,{...config.defaults,lintCommand:'',testCommand:'',maxVerificationRuns:3});
    write('no-tests.cjs','const ok = 1;\n');none.observe({name:'write_file',ok:true,data:{path:'no-tests.cjs'}});
    assert.equal((await none.flush()).status,'partial','Missing lint/test is never verified');
    const timeout = new CodeVerifier(root,settings,{run:async()=>({ok:false,timedOut:true,skipped:false,output:'',exitCode:null})});
    timeout.observe({name:'edit_file',ok:true,data:{path:'calc.cjs'}});
    assert.equal((await timeout.flush()).verified,false);assert.equal(timeout.blocked(),true);
    const changesDuringCheck = new CodeVerifier(root,settings,{run:async()=>{write('tsconfig.json','{"strict":false}');return{ok:true,skipped:false,timedOut:false,output:'',exitCode:0};}});
    changesDuringCheck.observe({name:'edit_file',ok:true,data:{path:'calc.cjs'}});
    assert.equal((await changesDuringCheck.flush()).status,'stale','A mutating checker cannot stamp a different version');
    const controller=new AbortController();controller.abort();
    const cancelled=new CodeVerifier(root,settings);cancelled.observe({name:'edit_file',ok:true,data:{path:'calc.cjs'}});
    assert.equal((await cancelled.flush(controller.signal)).status,'cancelled');
    const snapshot=captureInputs(root);assert.equal(snapshot.complete,true);
    const shell=new CodeVerifier(root,settings);
    shell.beginRound([{name:'execute_shell'}]);write('new-shell.cjs','module.exports = 1;\n');shell.endRound();
    assert.equal(shell.dirty.has('new-shell.cjs'),true,'Shell changes enter the same validation batch');
    write('.env','PRIVATE_VALUE=one');const a=captureInputs(root);write('.env','PRIVATE_VALUE=two');const b=captureInputs(root);
    assert.notEqual(a.fingerprint,b.fingerprint,'Environment configuration changes invalidate receipts');
    assert.equal(b.entries.get('.env').text,'','Sensitive configuration contributes only a hash');
    fs.mkdirSync(path.join(root,'src/release'),{recursive:true});write('src/release/source.cjs','module.exports = 1;');
    assert.equal(captureInputs(root).entries.has('src/release/source.cjs'),true,'Nested business release folders remain inputs');
    fs.symlinkSync(path.join(root,'src'),path.join(root,'linked-source'),process.platform==='win32'?'junction':'dir');
    assert.equal(captureInputs(root).complete,false,'Untracked source links cannot produce a verified receipt');
    fs.unlinkSync(path.join(root,'linked-source'));
    const denied=new CodeVerifier(root,settings,{allowCommands:false,run:async()=>{throw Error('Must not execute denied commands');}});
    denied.observe({name:'edit_file',ok:true,data:{path:'calc.cjs'}});assert.equal((await denied.flush()).verified,false);
    write('odd%name.cjs','const ok = 1;\n');
    const independent=new CodeVerifier(root,{...settings,testCommand:'node -e "process.exit(0)"'},{policy,context});
    independent.observe({name:'write_file',ok:true,data:{path:'odd%name.cjs'}});
    assert.equal((await independent.flush()).status,'passed','Commands without files placeholders do not need filename interpolation');
    console.log('CODING SAFETY: PASS (unique/batch atomic replacement, syntax and truncation guards, CAS, BOM/CRLF, settings, real related tests, hash freshness, timeout/cancel/partial/budget defence)');
  } finally { require(path.join(moduleRoot,'electron/rag/index.cjs')).clearIndexCache(); fs.rmSync(root,{recursive:true,force:true}); }
}
module.exports={main};
if(require.main===module)main().catch(error=>{console.error(error);process.exitCode=1;});

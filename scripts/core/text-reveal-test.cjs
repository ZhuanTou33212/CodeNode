'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const Module = require('node:module');
const ts = require('@typescript/typescript6');
function load(relative) {
  const file = path.join(__dirname, "../..", relative);
  const loaded = new Module(file, module);
  loaded.filename = file;
  /** @type {any} */
  const internal = loaded;
  internal._compile(ts.transpileModule(fs.readFileSync(file, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020, esModuleInterop: true }, fileName: file }).outputText, file);
  return loaded.exports;
}
const { TextReveal } = load('src/lib/textReveal.ts');
const prefs = load('src/lib/uiPreferences.ts');
const ui = require("../../config/ui.output.json");
assert.equal(prefs.normalizeUiPreferences({}).typewriterEnabled, true);
assert.equal(prefs.normalizeUiPreferences({}).typewriterCharsPerSecond, 60);
assert.equal(prefs.normalizeUiPreferences({typewriterEnabled:false,typewriterCharsPerSecond:999}).typewriterCharsPerSecond, ui.charactersPerSecond.max);
assert.equal(prefs.normalizeUiPreferences({typewriterCharsPerSecond:-1}).typewriterCharsPerSecond, ui.charactersPerSecond.min);
const display = new TextReveal();
display.update('你好世界，这是逐字显示。');
assert.equal(display.advance(0, 60, 3000), '你');
assert.equal(display.advance(17, 60, 3000), '你好');
assert.ok(display.pending);
display.update('你好世界，这是逐字显示。新分片');
for (let now = 34; now < 1000; now += 17) display.advance(now, 60, 3000);
assert.equal(display.text, display.target); assert.equal(display.pending, false);
const unicode = new TextReveal();
unicode.update('👨‍👩‍👧‍👦é🚀');
assert.equal(unicode.advance(0, 20, 3000), '👨‍👩‍👧‍👦');
assert.equal(unicode.advance(50, 20, 3000), '👨‍👩‍👧‍👦é');
assert.equal(unicode.advance(100, 20, 3000), unicode.target);
const halves = new TextReveal();
halves.update('A\ud83d'); assert.equal(halves.advance(0, 20, 3000), 'A');
halves.update('A\ud83d\ude80'); assert.equal(halves.advance(50, 20, 3000), 'A🚀');
display.update('相同开头旧内容'.repeat(40)); display.advance(0, 20, 3000);
display.update('相同开头新的响应', 1);
assert.equal(display.text, '', 'A reset revision clears even a matching prefix');
assert.equal(display.advance(0, 20, 3000), '相');
assert.equal(display.flush(), '相同开头新的响应');
assert.equal(new TextReveal('历史消息').text, '历史消息', 'Loaded messages start complete');
const long = new TextReveal(); long.update('长'.repeat(10000));
for (let now = 0; now < 3500; now += 16) long.advance(now, 20, 3000);
assert.equal(long.pending, false, 'A long provider chunk must not create minutes of display lag');
console.log('TEXT REVEAL: PASS (pace, appends, grapheme/surrogate boundaries, reset, flush, history, catchup and persistent preference normalization)');
